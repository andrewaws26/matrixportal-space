def latlon_to_pixel(lat, lon):
    """Convert lat/lon to pixel coordinates on the 64x32 map."""
    x = int((lon - LON_LEFT) / (LON_RIGHT - LON_LEFT) * MAP_W)
    y = int((LAT_TOP - lat) / (LAT_TOP - LAT_BOT) * MAP_H)
    return max(0, min(MAP_W - 1, x)), max(0, min(MAP_H - 1, y))


def get_continent(x, y):
    """Return continent ID at pixel (x, y). 0=ocean."""
    if 0 <= x < MAP_W and 0 <= y < MAP_H:
        return MAP_PIXELS[y * MAP_W + x]
    return 0


def init_map(bitmap):
    """Write the world map into a displayio.Bitmap using continent IDs."""
    for y in range(MAP_H):
        for x in range(MAP_W):
            c = MAP_PIXELS[y * MAP_W + x]
            if c > 0:
                bitmap[x, y] = c
